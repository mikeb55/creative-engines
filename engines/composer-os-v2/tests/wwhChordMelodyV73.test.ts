import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { alignChordMelody } from '../core/wwh/director/chordMelodyAlign';
import { guitarOnlyChordMelody } from '../core/wwh/director/chordMelodyScore';
import { executePerformancePlan } from '../core/wwh/director/executePerformancePlan';
import { proposeFullChordMelody, proposeMixedChordMelody } from '../core/wwh/director/proposeChordMelody';
import { proposeSourceClosePlan } from '../core/wwh/director/proposePerformancePlan';
import { indexSource } from '../core/wwh/director/sourceIndexAdapter';
import { bindAndValidatePlan, PerformancePlanBindError } from '../core/wwh/director/validatePerformancePlan';
import { importWwhDuoMusicXml, type WwhImportedMeasure } from '../core/wwh/wwhDuoImport';

const ROOT = '/Users/user/Documents/DEVS/ECM-Album-Nov-2027/00 - WWH DUO LEADSHEETS';
const CM = `${ROOT}/CHORD MELODIES WWH/Chord Melodies Generated by Composer`;
const BLACK_DUO = `${ROOT}/01-Black-Aura-Duo-Leadsheet-V1.1.musicxml`;
const BLACK_CM = `${CM}/01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.1.musicxml`;
const BLACK_V10 = `${CM}/01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.0.musicxml`;
const MIRROR_DUO = `${ROOT}/03-The-Mirror-Duo-Leadsheet-V1.0.musicxml`;
const MIRROR_CM = `${CM}/03-The-Mirror-COMPOSER-OS-Alternate-Arrangement-V1.0.musicxml`;

function read(file: string): { xml: string; sha: string } {
  const xml = fs.readFileSync(file, 'utf8');
  return { xml, sha: createHash('sha256').update(xml).digest('hex') };
}

function signature(measure: WwhImportedMeasure): string {
  return measure.notes
    .map((note) =>
      [
        note.voice,
        note.chord ? 'c' : 'a',
        note.rest ? 'R' : `${note.step}${note.alter ?? 0}${note.octave}`,
        note.duration,
        note.type,
        note.dots,
        note.tieStart ? 's' : '',
        note.tieStop ? 't' : '',
      ].join(':')
    )
    .join('|');
}

function guitarPart(xml: string): string {
  const match = xml.match(/<part id="[^"]+">[\s\S]*?<\/part>/);
  if (!match) throw new Error('missing part');
  return match[0];
}

const blackDuo = read(BLACK_DUO);
const blackCm = read(BLACK_CM);
const blackV10 = read(BLACK_V10);
const mirrorDuo = read(MIRROR_DUO);
const mirrorCm = read(MIRROR_CM);
const blackIndex = indexSource(blackDuo.xml, blackDuo.sha);
const blackArrangement = indexSource(blackCm.xml, blackCm.sha);
const mirrorIndex = indexSource(mirrorDuo.xml, mirrorDuo.sha);
const mirrorArrangement = indexSource(mirrorCm.xml, mirrorCm.sha);

const blackAlign = alignChordMelody(blackIndex, blackArrangement);
assert.equal(blackAlign.ok, true, blackAlign.message);
assert.equal(blackAlign.pairs.length, 39);
assert.deepEqual(blackAlign.pairs[0], { duoOrder: 0, arrangementOrder: 1 });
assert.deepEqual(blackAlign.excludedArrangementOrders, [0, 40]);

const mirrorAlign = alignChordMelody(mirrorIndex, mirrorArrangement);
assert.equal(mirrorAlign.ok, true, mirrorAlign.message);
assert.equal(mirrorAlign.pairs.length, 68);
assert.deepEqual(mirrorAlign.pairs[0], { duoOrder: 0, arrangementOrder: 0 });
assert.deepEqual(mirrorAlign.excludedArrangementOrders, []);

const v10 = alignChordMelody(blackIndex, indexSource(blackV10.xml, blackV10.sha));
assert.notEqual(blackV10.sha, blackCm.sha);

const beforeGuitar = guitarPart(blackCm.xml);
const guitarOnly = guitarOnlyChordMelody(blackCm.xml, 'Black Aura — Chord Melody — guitar only');
assert.equal(guitarPart(guitarOnly), beforeGuitar);
assert.equal(/<part-name>Upright Bass<\/part-name>|<part-name>Bass<\/part-name>/i.test(guitarOnly), false);
assert.equal((guitarOnly.match(/<part /g) ?? []).length, 1);
assert.equal(fs.readFileSync(BLACK_CM, 'utf8'), blackCm.xml);

const full = proposeFullChordMelody(blackIndex, blackArrangement, 'black-aura-v73-chord-melody-duo');
const fullRun = executePerformancePlan(blackDuo.xml, full, blackDuo.sha, 'Black-Aura-CM-DUO', blackCm.xml);
assert.equal(fullRun.compiled.bars.length, 39);
assert.equal(fullRun.compiled.receipt.materials.find((row) => row.player === 'guitar')?.status, 'CHORD_MELODY_REALIZED');
assert.equal(fullRun.compiled.receipt.materials.find((row) => row.player === 'bass')?.status, 'SOURCE_REALIZED');
const fullScore = importWwhDuoMusicXml(fullRun.scores.performance);
fullScore.guitar.measures.forEach((measure, index) => {
  assert.equal(signature(measure), signature(blackArrangement.measures[index + 1]!.guitar), `guitar bar ${index + 1}`);
  assert.equal(signature(fullScore.bass.measures[index]!), signature(blackIndex.measures[index]!.bass), `bass bar ${index + 1}`);
});

const mixed = proposeMixedChordMelody(blackIndex, blackArrangement, 'black-aura-v73-chord-melody-mixed', 7);
const mixedRun = executePerformancePlan(blackDuo.xml, mixed, blackDuo.sha, 'Black-Aura-CM-MIXED', blackCm.xml);
assert.equal(mixedRun.compiled.bars.length, 39);
const mixedScore = importWwhDuoMusicXml(mixedRun.scores.performance);
mixedScore.guitar.measures.forEach((measure, index) => {
  const expected = index < 8 ? blackIndex.measures[index]!.guitar : blackArrangement.measures[index + 1]!.guitar;
  assert.equal(signature(measure), signature(expected), `mixed guitar ${index + 1}`);
});
const uses = mixedRun.compiled.receipt.sourceMap.filter((row) => row.player === 'guitar').map((row) => row.use);
assert.deepEqual(new Set(uses.slice(0, 8)), new Set(['primary']));
assert.deepEqual(new Set(uses.slice(8)), new Set(['chord_melody']));

const mirrorFull = proposeFullChordMelody(mirrorIndex, mirrorArrangement, 'mirror-v73-chord-melody-duo');
const mirrorRun = executePerformancePlan(mirrorDuo.xml, mirrorFull, mirrorDuo.sha, 'Mirror-CM-DUO', mirrorCm.xml);
assert.equal(mirrorRun.compiled.bars.length, 68);
const mirrorScore = importWwhDuoMusicXml(mirrorRun.scores.performance);
mirrorScore.guitar.measures.forEach((measure, index) => {
  assert.equal(signature(measure), signature(mirrorArrangement.measures[index]!.guitar), `mirror guitar ${index + 1}`);
  assert.equal(signature(mirrorScore.bass.measures[index]!), signature(mirrorIndex.measures[index]!.bass), `mirror bass ${index + 1}`);
});
const mirrorOnly = guitarOnlyChordMelody(mirrorCm.xml, 'The Mirror — chord melody — guitar only');
assert.equal(guitarPart(mirrorOnly), guitarPart(mirrorCm.xml));
assert.equal((mirrorOnly.match(/<score-part /g) ?? []).length, 1);

const plain = proposeSourceClosePlan(blackIndex, 'black-aura-v73a-source-close');
const plainRun = executePerformancePlan(blackDuo.xml, plain, blackDuo.sha);
assert.equal(plainRun.compiled.receipt.sourceMap.some((row) => row.use === 'chord_melody'), false);

const broken = structuredClone(full);
const gap = blackArrangement.measures[0]!.id;
if (broken.sections[0]?.voices.guitar.material.kind === 'chord_melody') {
  broken.sections[0].voices.guitar.material.arrangementSpan.firstMeasureId = gap;
}
assert.throws(() => bindAndValidatePlan(broken, blackIndex, blackArrangement), PerformancePlanBindError);

const wrongFile = structuredClone(full);
assert.throws(() => bindAndValidatePlan(wrongFile, blackIndex, indexSource(blackV10.xml, blackV10.sha)), (error: unknown) => {
  assert.ok(error instanceof PerformancePlanBindError);
  assert.ok(error.errors.some((item) => item.code === 'ARRANGEMENT_HASH'));
  return true;
});

console.log(`PASS chord-melody V1.0 alignment ${v10.ok ? 'exists but is not selected' : 'absent'}`);
console.log('PASS WWH V7.3 chord-melody integration');
