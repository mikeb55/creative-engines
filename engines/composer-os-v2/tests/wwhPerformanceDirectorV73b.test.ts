function note(step: string, octave: number, dur: number, type: string): string {
  return `<note><pitch><step>${step}</step><octave>${octave}</octave></pitch><duration>${dur}</duration><voice>1</voice><type>${type}</type></note>`;
}

function attrs(clef: 'G' | 'F', beats: number, beatType: number, divisions: number): string {
  const sign = clef;
  const line = clef === 'G' ? 2 : 4;
  return `<attributes><divisions>${divisions}</divisions><key><fifths>0</fifths><mode>major</mode></key><time><beats>${beats}</beats><beat-type>${beatType}</beat-type></time><clef><sign>${sign}</sign><line>${line}</line></clef></attributes>`;
}

function duo(beats: number, beatType: number, divisions: number): string {
  const ticks = Math.round((divisions * beats * 4) / beatType);
  const type = beatType === 8 ? 'eighth' : 'quarter';
  const body = Array.from({ length: beats }, () => note('C', 4, Math.round(ticks / beats), type)).join('');
  const bass = Array.from({ length: beats }, () => note('C', 3, Math.round(ticks / beats), type)).join('');
  const bars = [0, 1, 2, 3]
    .map((index) => {
      const head = index === 0 ? attrs('G', beats, beatType, divisions) : '';
      const headB = index === 0 ? attrs('F', beats, beatType, divisions) : '';
      return { g: `${head}${body}`, b: `${headB}${bass}` };
    });
  const part = (which: 'g' | 'b') => bars.map((bar, index) => `<measure number="${index + 1}">${bar[which]}</measure>`).join('');
  return `<?xml version="1.0" encoding="UTF-8"?>
<score-partwise version="3.1"><work><work-title>Meter</work-title></work>
<part-list><score-part id="P1"><part-name>Electric Guitar</part-name></score-part><score-part id="P2"><part-name>Upright Bass</part-name></score-part></part-list>
<part id="P1">${part('g')}</part><part id="P2">${part('b')}</part></score-partwise>`;
}

function sched(run: ReturnType<typeof executePerformancePlan>, id: string): SectionSchedule {
  const found = run.compiled.receipt.schedule?.find((item) => item.sectionId === id);
  if (!found) throw new Error(`missing schedule ${id}`);
  return found;
}

function placed(run: ReturnType<typeof executePerformancePlan>, id: string): { barCount: number; firstOutputBar: number } {
  const found = run.compiled.receipt.sections.find((item) => item.id === id);
  if (!found) throw new Error(`missing section ${id}`);
  return found;
}

function pointKey(section: SectionSchedule, player: 'guitar' | 'bass', edge: 'entry' | 'exit'): string {
  const at = section[player][edge];
  return `${at.bar}:${at.offsetQ.n}/${at.offsetQ.d}`;
}

function notation(run: ReturnType<typeof executePerformancePlan>, sectionId: string, player: 'guitar' | 'bass'): string {
  return run.compiled.receipt.sourceMap
    .filter((row) => row.sectionId === sectionId && row.player === player)
    .map((row) => row.notation)
    .join(',');
}

function primary(run: ReturnType<typeof executePerformancePlan>, player: 'guitar' | 'bass'): string {
  return run.compiled.receipt.sourceMap
    .filter((row) => row.player === player && (row.use === 'primary' || row.use === 'chord_melody'))
    .map((row) => row.sourceMeasureId)
    .join(',');
}

function sig(measure: WwhImportedMeasure): string {
  return measure.notes
    .map((item) => [item.voice, item.chord ? 'c' : 'a', item.rest ? 'r' : item.step, item.alter ?? 0, item.octave ?? '', item.duration, item.tieStart ? 's' : '', item.tieStop ? 't' : ''].join(':'))
    .join('|');
}

function run(): { ok: boolean; name: string }[] {
  const rows: { ok: boolean; name: string }[] = [];
  const check = (name: string, fn: () => void) => {
    try {
      fn();
      rows.push({ ok: true, name });
    } catch (error) {
      rows.push({ ok: false, name: `${name} — ${error instanceof Error ? error.message : String(error)}` });
    }
  };

  const blackXml = fs.readFileSync(BLACK, 'utf8');
  const blackBefore = createHash('sha256').update(blackXml).digest('hex');
  const mirrorXml = fs.readFileSync(MIRROR, 'utf8');
  const mirrorCmXml = fs.readFileSync(MIRROR_CM, 'utf8');
  const black = indexSource(blackXml, blackBefore);
  const mirror = indexSource(mirrorXml);
  const mirrorCm = indexSource(mirrorCmXml);
  const planA = proposeBlackAuraPlanA(black);
  const planB = proposeBlackAuraPlanB(black);
  const planC = proposeMirrorPlanC(mirror, mirrorCm);

  check('V7.3A still rejects cue windows', () => {
    assert.throws(() => parsePerformancePlan({ ...planA, engineEdition: '7.3' }), PerformancePlanSchemaError);
  });

  check('circular cue dependency fails', () => {
    const broken = structuredClone(planA);
    const release = broken.sections.find((section) => section.id === 'invite')?.cues.find((cue) => cue.id === 'bass-release');
    if (!release) throw new Error('missing cue');
    release.prerequisites = ['guitar-answer'];
    assert.throws(() => bindAndValidatePlan(broken, black), PerformancePlanBindError);
  });

  check('locked leadership edit fails', () => {
    assert.throws(() => retargetLeadership(planA, 'src-before', 'guitar'), (error: unknown) => {
      assert.ok(error instanceof PlanMutationError);
      assert.equal(error.code, 'LOCK');
      return true;
    });
  });

  check('Plan A cue pulse moves the guitar entrance and leaves source bars put', () => {
    const before = executePerformancePlan(blackXml, planA, black.sha256, 'a');
    const afterPlan = moveCueByPulse(planA, 'bass-release', black);
    const after = executePerformancePlan(blackXml, afterPlan, black.sha256, 'a-cue');
    const left = sched(before, 'invite');
    const right = sched(after, 'invite');
    assert.notEqual(pointKey(left, 'guitar', 'entry'), pointKey(right, 'guitar', 'entry'));
    assert.equal(left.barCount, right.barCount);
    assert.equal(placed(before, 'src-before').barCount, placed(after, 'src-before').barCount);
    assert.equal(placed(before, 'src-return').firstOutputBar, placed(after, 'src-return').firstOutputBar);
    assert.equal(primary(before, 'guitar'), primary(after, 'guitar'));
    assert.equal(primary(before, 'bass'), primary(after, 'bass'));
    assert.equal(before.compiled.bars.filter((bar) => bar.sectionId === 'src-before').length, 8);
    assert.ok(before.scores.guitar_study.includes('MINIMAL'));
    assert.ok(before.scores.guitar_study.includes('LYRICAL'));
    assert.ok(before.scores.guitar_study.includes('ADVENTUROUS'));
    assert.ok(before.scores.performance.includes('slash'));
    assert.ok(before.scores.performance.includes('TACET') || before.scores.performance.includes('tacet') || before.scores.performance.includes('<rest/>'));
    const report = describeMutation({
      name: 'Plan A Test A',
      claim: 'Bass release moved one pulse. Guitar entrance moved. Return bar and source ids stayed.',
      before: before.compiled,
      after: after.compiled,
      sectionId: 'invite',
      passed: true,
    });
    assert.equal(report.status, 'PASS');
  });

  check('Plan A cycle count moves the return', () => {
    const before = executePerformancePlan(blackXml, planA, black.sha256);
    const after = executePerformancePlan(blackXml, setPreviewCycles(planA, 'invite', 5), black.sha256);
    assert.equal(sched(before, 'invite').barCount, 4);
    assert.equal(sched(after, 'invite').barCount, 5);
    assert.equal(placed(after, 'src-return').firstOutputBar, placed(before, 'src-return').firstOutputBar + 1);
    assert.equal(pointKey(sched(before, 'invite'), 'guitar', 'entry'), pointKey(sched(after, 'invite'), 'guitar', 'entry'));
    const returnBar = after.compiled.bars.find((bar) => bar.sectionId === 'src-return');
    const source = black.measures[8];
    assert.ok(returnBar && source);
    assert.equal(returnBar.beats, source.guitar.beats);
    assert.equal(returnBar.beatType, source.guitar.beatType);
    assert.equal(returnBar.divisions, source.guitar.divisions);
    assert.equal(returnBar.tempo.perMinute, source.guitar.tempo.perMinute);
    assert.equal(returnBar.tempo.beatUnit, source.guitar.tempo.beatUnit);
  });

  check('Plan A leadership changes ownership and listening, a role label does not', () => {
    const before = executePerformancePlan(blackXml, planA, black.sha256);
    const led = retargetLeadership(planA, 'invite', 'guitar');
    const after = executePerformancePlan(blackXml, led, black.sha256);
    assert.equal(sched(after, 'invite').leadership, 'guitar');
    assert.notEqual(notation(before, 'invite', 'guitar'), notation(after, 'invite', 'guitar'));
    assert.ok(sched(after, 'invite').cues.some((cue) => cue.cueId === 'bass-release' && cue.owner === 'guitar'));
    const labeled = structuredClone(planA);
    const invite = labeled.sections.find((section) => section.id === 'invite');
    if (!invite) throw new Error('missing invite');
    invite.voices.guitar.role = 'lead';
    invite.voices.bass.role = 'support';
    const same = executePerformancePlan(blackXml, labeled, black.sha256);
    assert.equal(notation(before, 'invite', 'guitar'), notation(same, 'invite', 'guitar'));
    assert.equal(notation(before, 'invite', 'bass'), notation(same, 'invite', 'bass'));
    assert.equal(pointKey(sched(before, 'invite'), 'guitar', 'entry'), pointKey(sched(same, 'invite'), 'guitar', 'entry'));
  });

  check('Plan A chord-melody switch is blocked', () => {
    assert.throws(() => setGuitarMaterial(planA, 'src-before', 'chord_melody'), (error: unknown) => {
      assert.ok(error instanceof PlanMutationError);
      assert.equal(error.code, 'UNAUTHORISED');
      return true;
    });
  });

  check('Plan B interruption is not Plan A with swapped names', () => {
    const a = executePerformancePlan(blackXml, planA, black.sha256);
    const b = executePerformancePlan(blackXml, planB, black.sha256);
    assert.equal(sched(a, 'invite').leadership, 'bass');
    assert.equal(sched(b, 'g-lead').leadership, 'guitar');
    assert.ok(sched(b, 'g-lead').cues.some((cue) => cue.behaviour === 'stop'));
    assert.ok(!sched(a, 'invite').cues.some((cue) => cue.behaviour === 'stop'));
    assert.equal(sched(b, 'g-lead').barCount < sched(b, 'g-lead').plannedBarCount, true);
    assert.equal(primary(b, 'guitar').split(',').length, 39);
    const before = b;
    const moved = executePerformancePlan(blackXml, moveCueByPulse(planB, 'bass-interrupt', black), black.sha256);
    assert.notEqual(pointKey(sched(before, 'g-lead'), 'guitar', 'exit'), pointKey(sched(moved, 'g-lead'), 'guitar', 'exit'));
    assert.notEqual(placed(before, 'src-return').firstOutputBar, placed(moved, 'src-return').firstOutputBar);
    assert.equal(placed(before, 'src-before').firstOutputBar, placed(moved, 'src-before').firstOutputBar);
    assert.equal(placed(before, 'src-before').barCount, placed(moved, 'src-before').barCount);
    assert.equal(primary(before, 'guitar'), primary(moved, 'guitar'));
    const longer = executePerformancePlan(blackXml, setPreviewCycles(planB, 'hold', 3), black.sha256);
    assert.equal(sched(longer, 'hold').barCount, sched(before, 'hold').barCount + 1);
    assert.equal(sched(longer, 'g-lead').barCount, sched(before, 'g-lead').barCount);
    assert.equal(placed(longer, 'src-return').firstOutputBar, placed(before, 'src-return').firstOutputBar + 1);
    const led = executePerformancePlan(blackXml, retargetLeadership(planB, 'hold', 'guitar'), black.sha256);
    assert.notEqual(notation(before, 'hold', 'bass'), notation(led, 'hold', 'bass'));
    assert.equal(sched(led, 'hold').cues[0]?.owner, 'guitar');
  });

  check('Plan C keeps 68 bars, copies chord melody, and mutations stay local', () => {
    const before = executePerformancePlan(mirrorXml, planC, mirror.sha256, 'c', mirrorCmXml);
    assert.equal(primary(before, 'guitar').split(',').length, 68);
    assert.equal(primary(before, 'bass').split(',').length, 68);
    const lead = importWwhDuoMusicXml(before.scores.leadsheet);
    assert.equal(compareLockedSpan(mirror.score.guitar.measures, lead.guitar.measures, 'guitar lead').length, 0);
    assert.equal(compareLockedSpan(mirror.score.bass.measures, lead.bass.measures, 'bass lead').length, 0);
    const moved = executePerformancePlan(mirrorXml, moveCueByPulse(planC, 'mirror-bass-release', mirror), mirror.sha256, 'c-cue', mirrorCmXml);
    assert.notEqual(pointKey(sched(before, 'dialogue'), 'guitar', 'entry'), pointKey(sched(moved, 'dialogue'), 'guitar', 'entry'));
    assert.equal(placed(before, 'src-return').firstOutputBar, placed(moved, 'src-return').firstOutputBar);
    assert.equal(primary(before, 'bass'), primary(moved, 'bass'));
    const longer = executePerformancePlan(mirrorXml, setPreviewCycles(planC, 'dialogue', 4), mirror.sha256, 'c-bars', mirrorCmXml);
    assert.equal(sched(longer, 'dialogue').barCount, sched(before, 'dialogue').barCount + 1);
    assert.equal(placed(longer, 'src-return').firstOutputBar, placed(before, 'src-return').firstOutputBar + 1);
    const returnBar = longer.compiled.bars.find((bar) => bar.sectionId === 'src-return');
    const cmEnd = planC.sections.find((section) => section.id === 'cm-span');
    const returnMeasure = mirror.byId.get(planC.sections.find((section) => section.id === 'src-return')?.primarySourceSpan?.firstMeasureId ?? '');
    assert.ok(returnBar && returnMeasure && cmEnd);
    assert.equal(returnBar.beats, returnMeasure.guitar.beats);
    assert.equal(returnBar.beatType, returnMeasure.guitar.beatType);
    assert.equal(returnBar.divisions, returnMeasure.guitar.divisions);
    assert.equal(returnBar.tempo.perMinute, returnMeasure.guitar.tempo.perMinute);
    const led = executePerformancePlan(mirrorXml, retargetLeadership(planC, 'dialogue', 'guitar'), mirror.sha256, 'c-lead', mirrorCmXml);
    assert.equal(sched(led, 'dialogue').leadership, 'guitar');
    assert.notEqual(notation(before, 'dialogue', 'guitar'), notation(led, 'dialogue', 'guitar'));
    const original = setGuitarMaterial(planC, 'cm-span', 'source');
    const sourceRun = executePerformancePlan(mirrorXml, original, mirror.sha256, 'c-src', mirrorCmXml);
    const perf = importWwhDuoMusicXml(before.scores.performance);
    const plain = importWwhDuoMusicXml(sourceRun.scores.performance);
    const cmRows = before.compiled.receipt.sourceMap.filter((row) => row.sectionId === 'cm-span' && row.player === 'guitar');
    assert.ok(cmRows.length >= 4);
    let changedBars = 0;
    cmRows.forEach((row) => {
      const arranged = mirrorCm.measures.find((measure) => measure.id === row.arrangementMeasureId);
      const duoMeasure = mirror.measures.find((measure) => measure.id === row.sourceMeasureId);
      assert.ok(arranged && duoMeasure);
      assert.equal(sig(perf.guitar.measures[row.outputBar - 1]!), sig(arranged.guitar));
      assert.equal(sig(perf.bass.measures[row.outputBar - 1]!), sig(duoMeasure.bass));
      assert.equal(sig(plain.guitar.measures[row.outputBar - 1]!), sig(duoMeasure.guitar));
      assert.equal(sig(plain.bass.measures[row.outputBar - 1]!), sig(duoMeasure.bass));
      if (sig(perf.guitar.measures[row.outputBar - 1]!) !== sig(plain.guitar.measures[row.outputBar - 1]!)) changedBars += 1;
    });
    assert.ok(changedBars > 0, 'authorised span did not change any guitar notes');
    const other = before.compiled.receipt.sourceMap.filter((row) => row.sectionId !== 'cm-span' && row.player === 'guitar' && row.use === 'primary');
    for (const row of other) {
      assert.equal(sig(perf.guitar.measures[row.outputBar - 1]!), sig(plain.guitar.measures[row.outputBar - 1]!));
    }
  });

  check('metres 3/4, 6/8 and 12/8 keep the cue grid', () => {
    for (const [beats, beatType, divisions] of [
      [3, 4, 256],
      [6, 8, 480],
      [12, 8, 480],
    ] as const) {
      const xml = duo(beats, beatType, divisions);
      const index = indexSource(xml);
      const plan = proposePulseWindow(index, `meter-${beats}-${beatType}`);
      const before = executePerformancePlan(xml, plan, index.sha256);
      const after = executePerformancePlan(xml, moveCueByPulse(plan, 'bass-release', index), index.sha256);
      assert.equal(before.compiled.bars[0]?.beats, beats);
      assert.equal(before.compiled.bars[0]?.beatType, beatType);
      assert.equal(before.compiled.bars[0]?.divisions, divisions);
      assert.notEqual(pointKey(sched(before, 'invite'), 'guitar', 'entry'), pointKey(sched(after, 'invite'), 'guitar', 'entry'));
      assert.equal(primary(before, 'guitar').split(',').filter(Boolean).length, 4);
      const twice = executePerformancePlan(xml, plan, index.sha256);
      assert.equal(before.scores.performance, twice.scores.performance);
    }
  });

  check('source bytes stay put', () => {
    assert.equal(createHash('sha256').update(fs.readFileSync(BLACK)).digest('hex'), blackBefore);
  });

  return rows;
}

const rows = run();
for (const row of rows) console.log(`${row.ok ? 'PASS' : 'FAIL'} ${row.name}`);
const failed = rows.filter((row) => !row.ok);
console.log(`${rows.length - failed.length}/${rows.length}`);
if (failed.length) process.exit(1);
