"""Black Aura chord-melody V1.1.

Reads the locked WWH continuous-playback source and writes one piece.
Melody, bass, harmony symbols, meter, tempo, form text, and the
5-second gaps stay. Guitar inner notes are a selective Wheeler line:
common tone, semitone or whole-step motion, open strings, source chords kept.

V1.0 (batch extract) is not overwritten.
"""

