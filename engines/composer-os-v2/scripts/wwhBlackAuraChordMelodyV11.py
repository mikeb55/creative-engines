OUT = OUT_DIR / "01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.1.musicxml"
REVIEW = OUT_DIR / "01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.1-REVIEW.md"

# measure, onset in divisions (256 = quarter), pitches below the melody (step, alter, octave)
ADDS: list[tuple[int, int, tuple[tuple[str, int, int], ...]]] = [
    (2, 768, (("C", 0, 4),)),       # Fm(add9): 5th under G. Open G + fret 3
    (3, 512, (("B", -1, 4),)),      # Bbsus2: C steps to Bb under Eb. Not an Ab triad
    (4, 512, (("B", 0, 4),)),       # Em(maj7): Bb rises to B under D
    (6, 512, (("C", 0, 4),)),       # VAR 2 Fm(add9): C returns under F
    (7, 512, (("C", 0, 4),)),       # Bbsus2: C under the Bb melody
    (8, 512, (("B", 0, 4),)),       # Em(maj7): B under G, open B
    (9, 512, (("D", 0, 4),)),       # Asus4: the 4th, open D, under B
    (10, 768, (("C", 0, 4),)),      # M2 answer, Fm 5th
    (11, 768, (("B", -1, 4),)),     # Bbsus2: C steps to Bb, same as m3
    (12, 768, (("B", 0, 4),)),      # open B under open E
    (13, 768, (("B", 0, 4),)),      # hold B under D
    (25, 512, (("E", 0, 4),)),      # Dsus2: the 2nd under D
    (26, 512, (("A", 0, 3),)),      # F: 3rd, open A, bass silent
    (27, 512, (("C", 0, 4),)),      # Fm/Ab: 5th under D
    (28, 0, (("A", -1, 4),)),       # Ab: 3rd under C, bass silent
    (33, 768, (("C", 0, 4),)),      # M1 head returns
    (34, 512, (("C", 0, 4),)),      # hold C under Eb
    (37, 256, (("E", -1, 5),)),     # peak: Eb fifth under Ab
    (38, 768, (("E", -1, 4),)),     # same Eb, octave down, into the chord
]

OPENS = (52, 57, 62, 67, 71, 76)  # written E A D G B E
ACC = {-2: "flat-flat", -1: "flat", 1: "sharp", 2: "sharp-sharp"}
DIV = 256


def spell_pitch(step: str, alter: int, octave: int) -> str:
    mark = {0: "", -1: "b", -2: "bb", 1: "#", 2: "##"}[alter]
    return f"{step}{mark}{octave}"


def midi(step: str, alter: int, octave: int) -> int:
    base = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}[step]
    return (octave + 1) * 12 + base + alter


def pitch_of(note: ET.Element) -> tuple[str, int, int] | None:
    p = note.find("pitch")
    if p is None:
        return None
    return (
        p.findtext("step") or "",
        int(p.findtext("alter") or 0),
        int(p.findtext("octave") or 0),
    )


def playable(midis: list[int]) -> tuple[bool, str]:
    """One note per string, fret 0–15, fretted fingers inside 4 frets.

    Prefer open strings, then a low position. Higher pitch sits on a higher
    string unless the note on the higher string is open.
    """
    n = len(midis)
    if n == 0 or n > 6:
        return False, "count"
    best = None
    names = ("E", "A", "D", "G", "B", "e")
    for mask in range(6**n):
        strings = []
        x = mask
        ok = True
        for _ in range(n):
            s = x % 6
            x //= 6
            if s in strings:
                ok = False
                break
            strings.append(s)
        if not ok:
            continue
        frets = []
        for s, m in zip(strings, midis):
            f = m - OPENS[s]
            if f < 0 or f > 15:
                ok = False
                break
            frets.append(f)
        if not ok:
            continue
        fretted = [f for f in frets if f > 0]
        span = (max(fretted) - min(fretted)) if fretted else 0
        if span > 4:
            continue
        order = sorted(range(n), key=lambda i: (midis[i], strings[i]))
        crossed = False
        for a, b in zip(order, order[1:]):
            if strings[a] > strings[b] and frets[a] != 0:
                crossed = True
                break
        if crossed:
            continue
        score = (-frets.count(0), max(frets) if frets else 0, span, sum(frets))
        if best is None or score < best[0]:
            best = (score, frets, strings)
    if best is None:
        return False, "no grip"
    frets, strings = best[1], best[2]
    if frets and max(frets) > 8:
        return False, "position " + " ".join(f"{names[s]}{f}" for s, f in zip(strings, frets))
    detail = " ".join(f"{names[s]}{f}" for s, f in zip(strings, frets))
    return True, detail


def sha(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def measure_map(part: ET.Element) -> dict[int, ET.Element]:
    return {int(m.get("number")): m for m in part.findall("measure")}


def insert_adds(guitar: ET.Element) -> list[str]:
    by_m = measure_map(guitar)
    lines = []
    for meas, onset, pitches in ADDS:
        m = by_m[meas]
        cursor = 0
        target = None
        for child in list(m):
            if child.tag != "note" or child.find("chord") is not None:
                continue
            if child.find("pitch") is not None and cursor == onset:
                target = child
                break
            cursor += int(child.findtext("duration") or 0)
        if target is None:
            raise SystemExit(f"no melody note at m{meas} onset {onset}")
        # do not touch a sonority that already has chord tones
        nxt = target.getnext() if hasattr(target, "getnext") else None
        # ElementTree has getnext in 3.8+? We'll scan siblings.
        kids = list(m)
        idx = kids.index(target)
        if idx + 1 < len(kids) and kids[idx + 1].find("chord") is not None:
            raise SystemExit(f"m{meas} already has a chord; refused")
        mel = pitch_of(target)
        assert mel is not None
        mel_m = midi(*mel)
        seen: dict[str, int] = {}
        for child in kids[: idx + 1]:
            if child.tag != "note":
                continue
            pp = pitch_of(child)
            if pp:
                seen[pp[0]] = pp[1]
        for step, alter, octave in pitches:
            if midi(step, alter, octave) >= mel_m:
                raise SystemExit(f"m{meas} inner note covers the melody")
            note = ET.Element("note")
            ET.SubElement(note, "chord")
            pe = ET.SubElement(note, "pitch")
            ET.SubElement(pe, "step").text = step
            if alter:
                ET.SubElement(pe, "alter").text = str(alter)
            ET.SubElement(pe, "octave").text = str(octave)
            ET.SubElement(note, "duration").text = target.findtext("duration")
            inst = ET.SubElement(note, "instrument")
            inst.set("id", "P1-I1")
            ET.SubElement(note, "voice").text = target.findtext("voice") or "1"
            ET.SubElement(note, "type").text = target.findtext("type")
            for _ in target.findall("dot"):
                ET.SubElement(note, "dot")
            acc = None
            if alter:
                acc = ACC[alter]
            elif seen.get(step, 0) != 0:
                acc = "natural"
            if acc:
                ET.SubElement(note, "accidental").text = acc
            ET.SubElement(note, "staff").text = target.findtext("staff") or "1"
            idx += 1
            m.insert(idx, note)
            seen[step] = alter
        grip_midis = [midi(*p) for p in pitches] + [mel_m]
        ok, detail = playable(grip_midis)
        if not ok:
            raise SystemExit(f"unplayable m{meas}: {detail} {grip_midis}")
        spell = " ".join(spell_pitch(*p) for p in pitches)
        lines.append(
            f"m{meas} beat {onset / DIV:g}: {spell_pitch(*mel)} + {spell} ({detail})"
        )
    return lines


def events(part: ET.Element, chord_notes: bool) -> list[tuple]:
    out = []
    for m in part.findall("measure"):
        n = int(m.get("number"))
        onset = 0
        for note in m.findall("note"):
            is_c = note.find("chord") is not None
            pp = pitch_of(note)
            dur = int(note.findtext("duration") or 0)
            if is_c and not chord_notes:
                continue
            if pp is None:
                if not is_c:
                    onset += dur
                continue
            out.append((n, onset if not is_c else onset, is_c, pp, dur))
            if not is_c:
                onset += dur
    return out


def harmony_text(part: ET.Element) -> list[str]:
    rows = []
    for m in part.findall("measure"):
        for h in m.findall("harmony"):
            rows.append(ET.tostring(h, encoding="unicode"))
    return rows


def words(part: ET.Element) -> list[str]:
    rows = []
    for m in part.findall("measure"):
        for w in m.findall(".//words"):
            rows.append((w.text or "").strip())
    return rows


def tempo_meter(part: ET.Element) -> list[tuple]:
    rows = []
    for m in part.findall("measure"):
        beats = m.findtext("attributes/time/beats")
        beat_type = m.findtext("attributes/time/beat-type")
        q = None
        for pm in m.findall(".//per-minute"):
            q = pm.text
        sound = m.find(".//sound")
        if sound is not None and sound.get("tempo"):
            q = sound.get("tempo")
        rows.append((m.get("number"), beats, beat_type, q))
    return rows


def main() -> None:
    before = sha(SRC)
    tree = ET.parse(SRC)
    root = tree.getroot()
    parts = root.findall("part")
    guitar, bass = parts[0], parts[1]
    # snapshot locks from the slice before edits
    for part in parts:
        for m in list(part.findall("measure")):
            if int(m.get("number")) > 41:
                part.remove(m)
    mel_before = events(guitar, False)
    bass_before = events(bass, True)
    harm_before = harmony_text(guitar)
    words_before = words(guitar)
    meter_before = tempo_meter(guitar)

    added_lines = insert_adds(guitar)

    root.find("work/work-title").text = "Black Aura — Chord Melody — Composer OS V1.1"
    root.find("movement-title").text = "1. Black Aura"
    desc = root.find("identification/encoding/encoding-description")
    if desc is not None:
        desc.text = (
            "Selective Wheeler chord-melody on locked V2.0 Black Aura, bars 1–41. "
            "Melody, bass, harmony symbols, meter, tempo, form text, and 5-second gaps unchanged."
        )
    misc = root.find("identification/miscellaneous")
    if misc is None:
        misc = ET.SubElement(root.find("identification"), "miscellaneous")
    field = ET.SubElement(misc, "miscellaneous-field")
    field.set("name", "WWH-chord-melody")
    field.text = "Black Aura V1.1. Inner line only. Source chords at m19, m39, m40 kept."

    mel_after = events(guitar, False)
    bass_after = events(bass, True)
    if mel_before != mel_after:
        raise SystemExit("melody lock failed")
    if bass_before != bass_after:
        raise SystemExit("bass lock failed")
    if harm_before != harmony_text(guitar):
        raise SystemExit("harmony lock failed")
    if words_before != words(guitar):
        raise SystemExit("text lock failed")
    if meter_before != tempo_meter(guitar):
        raise SystemExit("tempo/meter lock failed")

    # gaps
    for n in (1, 41):
        m = measure_map(guitar)[n]
        if any(note.find("pitch") is not None for note in m.findall("note")):
            raise SystemExit(f"gap m{n} not empty")
        mb = measure_map(bass)[n]
        if any(note.find("pitch") is not None for note in mb.findall("note")):
            raise SystemExit(f"bass gap m{n} not empty")

    # every simultaneous guitar sonority playable, melody not covered
    report_grips = []
    for m in guitar.findall("measure"):
        onset = 0
        cluster: list[tuple[int, bool]] = []

        def flush(on: int, cluster: list[tuple[int, bool]]) -> None:
            if not cluster:
                return
            midis = [t[0] for t in cluster]
            if any(c[0] > midis[0] for c in cluster[1:]):
                # primary is first; chord notes may be higher in the SOURCE ending
                pass
            tops = max(midis)
            # source ending and m19 put the lead as the lowest written note of a composed stack.
            # Those measures are copied, not arranged. Still require a grip.
            ok, detail = playable(midis)
            if not ok:
                raise SystemExit(f"unplayable sonority m{m.get('number')} onset {on}: {midis}")
            if len(midis) > 1:
                report_grips.append((int(m.get("number")), on / DIV, detail, len(midis)))

        for note in m.findall("note"):
            is_c = note.find("chord") is not None
            pp = pitch_of(note)
            dur = int(note.findtext("duration") or 0)
            if not is_c:
                flush(onset, cluster)
                cluster = []
                if pp:
                    cluster.append((midi(*pp), False))
                onset += dur
            elif pp:
                cluster.append((midi(*pp), True))
        flush(onset, cluster)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tree.write(OUT, encoding="utf-8", xml_declaration=True)
    after = sha(SRC)
    if before != after:
        raise SystemExit("source file changed")

    bare = [n for n in range(2, 41) if n not in {a[0] for a in ADDS} and n not in (19, 39, 40)]
    lines = [
        "# Black Aura chord-melody V1.1",
        "",
        "Source (unchanged): `V2.0-WWH-9-Chord-Melodies-Continuous-Playback-CORRECTED.musicxml`",
        f"Source SHA-256: `{before}`",
        "",
        "Output: `01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.1.musicxml`",
        "",
        "V1.0 is the batch extract. It is not this arrangement. Do not play V1.0.",
        "",
        "## Locks",
        "",
        "- Melody spine matches the source slice: yes",
        "- Bass matches: yes",
        "- Harmony symbols match: yes",
        "- Form text matches: yes",
        "- Meter and tempo match: yes",
        "- Bars 1–41, including the 5-second gaps at m1 and m41: yes",
        "- Source file hash unchanged: yes",
        "- Composed stacks kept: m19 F# A C, m39–40 G C F Ab",
        "",
        "## Inner line",
        "",
        "Wheeler colour inside the printed symbols. One grip on a long note, then air.",
        "Inner line: C, Bb, B, then C again, then B, then D. Later C returns with the M1 head.",
        "m14–18, m20–24, m29–32, m35–36 stay melody only.",
        "",
        "Bare bars: " + ", ".join(f"m{n}" for n in bare),
        "",
        "Added grips:",
        "",
    ]
    lines.extend(f"- {row}" for row in added_lines)
    lines += [
        "",
        "All guitar sonorities, including the kept stacks, have a standard-tuning grip. Fret 0–15. Fretted span at most 4.",
        "",
        f"Grips with more than one note: {len(report_grips)}",
        "",
        "## Not done",
        "",
        "- Sibelius was not opened. No PDF page was engraved or inspected.",
        "- Nobody played it.",
        "- This is not an official GCE receipt.",
        "",
    ]
    REVIEW.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"wrote {REVIEW}")
    print(f"adds {len(ADDS)} source {before[:16]} unchanged {before == after}")
    for row in added_lines:
        print(row)


if __name__ == "__main__":
    main()
