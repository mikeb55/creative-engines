/**
 * Write Black Aura and The Mirror chord-melody scores from existing arrangements.
 * Does not modify the source files.
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { alignChordMelody } from '../core/wwh/director/chordMelodyAlign';
import { guitarOnlyChordMelody } from '../core/wwh/director/chordMelodyScore';
import { executePerformancePlan } from '../core/wwh/director/executePerformancePlan';
import { proposeFullChordMelody, proposeMixedChordMelody } from '../core/wwh/director/proposeChordMelody';
import { indexSource } from '../core/wwh/director/sourceIndexAdapter';
import { auditWwhMusicXml } from '../core/wwh/wwhValidate';

const MSCORE = '/Applications/MuseScore 4.app/Contents/MacOS/mscore';
const ALBUM = '/Users/user/Documents/DEVS/ECM-Album-Nov-2027';
const LEAD = path.join(ALBUM, '00 - WWH DUO LEADSHEETS');
const GENERATED = path.join(LEAD, 'CHORD MELODIES WWH/Chord Melodies Generated by Composer');
const OUT = path.join(ALBUM, 'WWH-PERFORMANCE-MOCKUPS/V7.3-CHORD-MELODY');

function sha(file: string): string {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function renderScore(xmlPath: string, pngPath: string): { png: boolean; error: string } {
  if (!fs.existsSync(MSCORE)) return { png: false, error: 'MuseScore 4 CLI not found' };
  fs.mkdirSync(path.dirname(pngPath), { recursive: true });
  let error = '';
  try {
    execFileSync(MSCORE, ['-o', pngPath, xmlPath], { timeout: 120000, stdio: 'pipe' });
  } catch (caught) {
    error = caught instanceof Error ? caught.message.split('\n')[0] : String(caught);
  }
  const written = fs.existsSync(pngPath) || fs.existsSync(pngPath.replace(/\.png$/, '-1.png'));
  return { png: written, error };
}

function writePair(
  duoPath: string,
  arrangementPath: string,
  ids: { full: string; mixed: string; guitar: string },
  stems: { full: string; mixed: string; guitar: string },
  title: string,
  afterOrder: number
): string[] {
  const duoXml = fs.readFileSync(duoPath, 'utf8');
  const arrangementXml = fs.readFileSync(arrangementPath, 'utf8');
  const duo = indexSource(duoXml);
  const arrangement = indexSource(arrangementXml);
  const alignment = alignChordMelody(duo, arrangement);
  if (!alignment.ok) throw new Error(`${title}: ${alignment.message}`);
  const full = executePerformancePlan(duoXml, proposeFullChordMelody(duo, arrangement, ids.full), duo.sha256, stems.full, arrangementXml);
  const mixed = executePerformancePlan(
    duoXml,
    proposeMixedChordMelody(duo, arrangement, ids.mixed, afterOrder),
    duo.sha256,
    stems.mixed,
    arrangementXml
  );
  const guitarXml = guitarOnlyChordMelody(arrangementXml, `${title} — guitar only chord melody`);
  const dir = path.join(OUT, title.toLowerCase().replace(/\s+/g, '-'));
  fs.mkdirSync(dir, { recursive: true });
  const files = [
    ...full.files.map((file) => ({ ...file, name: path.join('duo', file.name) })),
    ...mixed.files.map((file) => ({ ...file, name: path.join('mixed', file.name) })),
    { name: `${stems.guitar}.musicxml`, contents: guitarXml },
  ];
  for (const file of files) {
    const target = path.join(dir, file.name);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file.contents);
  }
  for (const file of [...full.files, ...mixed.files].filter((item) => item.name.endsWith('.musicxml'))) {
    const audit = auditWwhMusicXml(file.contents, file.name);
    if (!audit.ok) throw new Error(audit.lines.join('\n'));
  }
  return [
    `## ${title}`,
    '',
    `Duo source \`${path.basename(duoPath)}\` \`${duo.sha256}\``,
    `Arrangement \`${path.basename(arrangementPath)}\` \`${arrangement.sha256}\``,
    alignment.message,
    `Excluded arrangement orders: ${alignment.excludedArrangementOrders.join(', ') || 'none'}`,
    `Duo bars ${full.compiled.bars.length}. Mixed bars ${mixed.compiled.bars.length}. Guitar-only keeps the arrangement staff and drops the bass staff.`,
    `Full plan \`${full.bound.planSha256}\`. Mixed plan \`${mixed.bound.planSha256}\`.`,
    '',
  ];
}

function main(): void {
  const locks = [BLACK_DUO, BLACK_CM, BLACK_V10, MIRROR_DUO, MIRROR_CM, BA_PARENT, MIRROR_PARENT].map((file) => [file, sha(file)] as const);
  const black = writePair(BLACK_DUO, BLACK_CM, {
    full: 'black-aura-v73-chord-melody-duo',
    mixed: 'black-aura-v73-chord-melody-mixed',
    guitar: 'guitar',
  }, {
    full: 'Black-Aura-V73-CM-DUO',
    mixed: 'Black-Aura-V73-CM-MIXED',
    guitar: 'Black-Aura-V73-CM-GUITAR-ONLY',
  }, 'Black Aura', 7);
  const mirror = writePair(MIRROR_DUO, MIRROR_CM, {
    full: 'mirror-v73-chord-melody-duo',
    mixed: 'mirror-v73-chord-melody-mixed',
    guitar: 'guitar',
  }, {
    full: 'Mirror-V73-CM-DUO',
    mixed: 'Mirror-V73-CM-MIXED',
    guitar: 'Mirror-V73-CM-GUITAR-ONLY',
  }, 'The Mirror', 7);
  const after = [BLACK_DUO, BLACK_CM, BLACK_V10, MIRROR_DUO, MIRROR_CM, BA_PARENT, MIRROR_PARENT].map((file) => sha(file));
  const unchanged = locks.every(([, hash], index) => hash === after[index]);
  const v10 = indexSource(fs.readFileSync(BLACK_V10, 'utf8'));
  const v10Align = alignChordMelody(indexSource(fs.readFileSync(BLACK_DUO, 'utf8')), v10);
  const parentSame = sha(BA_PARENT) === sha(BLACK_DUO);
  const mirrorParentSame = sha(MIRROR_PARENT) === sha(MIRROR_DUO);
  const renders = [
    ['black-aura/Black-Aura-V73-CM-GUITAR-ONLY.musicxml', 'render/black-aura-guitar.png'],
    ['black-aura/duo/Black-Aura-V73-CM-DUO-PERFORMANCE-PLAN-SCORE.musicxml', 'render/black-aura-duo.png'],
    ['black-aura/mixed/Black-Aura-V73-CM-MIXED-PERFORMANCE-PLAN-SCORE.musicxml', 'render/black-aura-mixed.png'],
    ['the-mirror/Mirror-V73-CM-GUITAR-ONLY.musicxml', 'render/mirror-guitar.png'],
    ['the-mirror/duo/Mirror-V73-CM-DUO-PERFORMANCE-PLAN-SCORE.musicxml', 'render/mirror-duo.png'],
    ['the-mirror/mixed/Mirror-V73-CM-MIXED-PERFORMANCE-PLAN-SCORE.musicxml', 'render/mirror-mixed.png'],
  ].map(([xml, png]) => ({ xml, ...renderScore(path.join(OUT, xml), path.join(OUT, png)) }));
  const report = [
    '# WWH V7.3 chord-melody validation',
    '',
    unchanged ? 'PASS source files unchanged.' : 'FAIL a source file changed.',
    '',
    ...black,
    ...mirror,
    '## Rejected substitutions',
    '',
    `Black Aura chord-melody V1.0 \`${v10.sha256}\` is not the authoritative arrangement. Alignment against the duo: ${v10Align.ok ? v10Align.message : v10Align.message}. It was not compiled.`,
    `\`01-Black-Aura-Duo-Chord-Melody-V1.0.musicxml\` ${parentSame ? 'is byte-identical to the duo leadsheet' : 'differs from the duo leadsheet'}. It is not a separate arrangement.`,
    `\`03-The-Mirror-Duo-Chord-Melody-V1.0.musicxml\` ${mirrorParentSame ? 'is byte-identical to the duo leadsheet' : 'differs from the duo leadsheet'}. It was not blended with the alternate arrangement.`,
    'Black Aura arrangement bars 1 and 41 are 5/4 gap rests. They remain in the guitar-only score and are excluded from the duo.',
    '',
    '## MuseScore 4',
    '',
    ...renders.map((row) => `- ${row.xml}: import/render ${row.png ? 'PNG written' : 'no PNG'}${row.error ? `; CLI ${row.error}` : ''}`),
    'Playback was not run.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(OUT, 'WWH-V7.3-CHORD-MELODY-VALIDATION.md'), report);
  console.log(report);
  if (!unchanged) process.exitCode = 1;
}

const BLACK_DUO = path.join(LEAD, '01-Black-Aura-Duo-Leadsheet-V1.1.musicxml');
const BLACK_CM = path.join(GENERATED, '01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.1.musicxml');
const BLACK_V10 = path.join(GENERATED, '01-Black-Aura-COMPOSER-OS-Chord-Melody-V1.0.musicxml');
const MIRROR_DUO = path.join(LEAD, '03-The-Mirror-Duo-Leadsheet-V1.0.musicxml');
const MIRROR_CM = path.join(GENERATED, '03-The-Mirror-COMPOSER-OS-Alternate-Arrangement-V1.0.musicxml');
const BA_PARENT = path.join(LEAD, 'CHORD MELODIES WWH/01-Black-Aura-Duo-Chord-Melody-V1.0.musicxml');
const MIRROR_PARENT = path.join(LEAD, 'CHORD MELODIES WWH/03-The-Mirror-Duo-Chord-Melody-V1.0.musicxml');

main();
