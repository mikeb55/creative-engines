export interface SongwriterStyleProfile {
  id: SongwriterRuleId;
  description?: string;
  /** 0–1 — emphasis on continuous line vs riff-like cells. */
  lineVsCellEmphasis: number;
  /** 0–1 — harmonic colour vs diatonic simplicity. */
  harmonyColourBias: number;
  /** 0–1 — form regularity (high = template pop). */
  formRegularity: number;
  /** 0–1 — lyric/prosody influence on phrasing. */
  prosodyInfluence: number;
  /** 0–1 — hook repetition / return strength. */
  hookRepetitionBias: number;
  /** 0–1 — phrase regularity (high = strict 4-bar, low = irregular/through-composed). */
  phraseRegularity: number;
  /** 0–1 — hook return variation (high = transformed return, low = literal repeat). */
  hookReturnVariation: number;
  /** 0–1 — harmonic speed (high = fast changes, low = slow/static). */
  harmonicSpeed: number;
  /** 0–1 — section contrast strength (high = dramatic shifts, low = subtle). */
  sectionContrast: number;
  /** 0–1 — rhythmic syncopation bias (high = heavy syncopation, low = on-beat). */
  syncopationBias: number;
  /** 0–1 — output density (high = dense layers, low = sparse). */
  densityBias: number;
  /** Typical motif cell size in notes (2–7). */
  motifCellSize?: number;
  /** Interval preference tag for motif generation. */
  intervalPreference?: 'stepwise' | 'triadic' | 'angular' | 'chromatic' | 'modal' | 'pentatonic' | 'mixed';
  /** Guitar lead interval preference tag. */
  guitarLeadIntervals?: string;
  /** Primary modal preference for guitar. */
  guitarModalPreference?: string;
  /** Fagen: probability of voicing major chords as Mu (add2) */
  fagenMuChordBias?: number;
  /** Fagen: probability of using maj7#11 on I and IV */
  fagenLydianMajorBias?: number;
  /** Fagen: probability of altered dominant on V chords */
  fagenAlteredDominantBias?: number;
  /** Fagen: strength of root avoidance in melody on strong beats */
  fagenRootAvoidanceMelody?: number;
  /** Fagen: probability of slash chord chains replacing plain V7 */
  fagenSlashChordDensity?: number;
  /** Bacharach: probability of deceptive cadence (V→vi or V→bVI) */
  bacharachDeceptiveCadenceRate?: number;
  /** Bacharach: strength of chromatic inner voice movement */
  bacharachChromaticVoiceLeading?: number;
  /** Bacharach: probability of borrowed chords (iv, bVI, bVII) */
  bacharachModalMixtureLevel?: number;
  /** Bacharach: probability of melody landing on non-tonic degree */
  bacharachCadentialAmbiguity?: number;
  /** Bacharach: probability of pedal point (static bass) */
  bacharachPedalUsage?: number;
  /** Human-readable label for UI / pairing hints (optional). */
  displayName?: string;
  /** Broad era bucket (e.g. singer-songwriter) for docs / pairing. */
  songwriterEraTag?: string;
  /** Primary melodic lead for receipts/UI (sax-led jazz, etc.). */
  primaryMelodicInstrument?: 'keys' | 'guitar' | 'sax' | 'ensemble' | 'winds' | 'bass';
  /** Multi-era harmonic lineage (e.g. Wayne Shorter periods). */
  songwriterHarmonicPeriods?: readonly string[];
  /** Engine routing hint — interval-set grammar vs chord-symbol rows. */
  songwriterSystemType?: 'interval_set' | 'chord_symbol' | 'hybrid' | 'blues_suite';
  /** Production-world gloss (0–1) — inherited from group defaults when omitted. */
  productionGloss?: number;
  /** Production-world melody framing — inherited from group defaults when omitted. */
  melodyFraming?: 'integrated' | 'spotlighted' | 'floating' | 'head_based';
}

