function finish(index: SourceIndex, id: string, sections: PlanSection[], motifs: PerformancePlan['motifs'], landmarks: PerformancePlan['identity']['returnLandmarks'], notes: string[], chordMelody: PerformancePlan['chordMelody']): PerformancePlan {
  const whole = spanOf(index, 0, index.measures.length - 1);
  const tail = spanOf(index, index.measures.length - 1, index.measures.length - 1);
  const final = sections[sections.length - 1];
  if (!final) throw new Error('plan needs a section');
  return {
    schemaVersion: '1.0',
    engineEdition: '7.3b',
    id,
    source: { scoreId: index.scoreId, sha256: index.sha256, partIds: { ...index.partIds }, annotationSha256: null },
    chordMelody,
    motifs,
    identity: {
      primaryTraversal: [whole],
      protectedSpans: [whole],
      requiredMotifIds: motifs.map((motif) => motif.id),
      returnLandmarks: [...landmarks, { id: 'written-ending', span: tail }],
    },
    sections,
    ending: { kind: 'source', finalSectionId: final.id, tail },
    practiceViews: [
      { id: 'guitar-study', product: 'guitar_study', sectionIds: sections.map((section) => section.id), focus: 'guitar', approaches: ['minimal', 'lyrical', 'adventurous'] },
      { id: 'bass-partner', product: 'bass_partner', sectionIds: sections.map((section) => section.id), focus: 'bass', approaches: ['minimal', 'lyrical', 'adventurous'] },
    ],
    notes,
  };
}

function motif(index: SourceIndex, id: string, player: 'guitar' | 'bass', first: number, last: number): PerformancePlan['motifs'][number] {
  const sourceEventIds = attacks(index, player, first, last);
  if (!sourceEventIds.length) throw new Error(`${index.title} ${id} has no ${player} attacks`);
  return { id, owner: player, span: spanOf(index, first, last), sourceEventIds, provenance: 'source_annotation', preserve: ['rhythm', 'contour'] };
}

function releaseCue(id: string, owner: Cue['owner'], bar: number, text: string, landmarkId: string, delay: Cue['responseDelay']): Cue {
  return {
    id,
    owner,
    action: 'release',
    target: owner === 'guitar' ? 'bass' : owner === 'bass' ? 'guitar' : 'both',
    trigger: { kind: 'at', point: { bar, offsetQ: ZERO.offsetQ } },
    printedText: text,
    prerequisites: [],
    responseDelay: delay ?? { minQ: ZERO.offsetQ, maxQ: ZERO.offsetQ, previewQ: ZERO.offsetQ },
    interruption: { behaviour: 'none' },
    returnLandmarkId: landmarkId,
  };
}

function openVoice(role: Role, material: VoicePlan['material'], entry: VoicePlan['entry'], exit: VoicePlan['exit'], density: 'sparse' | 'moderate'): VoicePlan {
  return { material, role, entry, exit, density: [{ at: ZERO, level: density }] };
}

interface WindowSpec {
  id: string;
  after: number;
  returnId: string;
  purpose: Purpose;
  mode: GuitarMode;
  leadership: 'guitar' | 'bass' | 'shared';
  cycleBars: number;
  minCycles: number;
  maxCycles: number;
  previewCycles: number;
  release: Cue;
  cues: Cue[];
  guitar: VoicePlan;
  bass: VoicePlan;
  motifIds: string[];
  rationale: string;
  relation: PerformancePlan['sections'][number]['exchanges'][number]['relation'];
}

function windowSection(index: SourceIndex, spec: WindowSpec): PlanSection {
  demandCut(index, spec.after);
  const template = spanOf(index, spec.after, spec.after);
  const exchangeCue = spec.cues[spec.cues.length - 1] ?? spec.release;
  return {
    id: spec.id,
    purpose: spec.purpose,
    length: {
      kind: 'cue_window',
      cycleBars: spec.cycleBars,
      minCycles: spec.minCycles,
      maxCycles: spec.maxCycles,
      previewCycles: spec.previewCycles,
      releaseCueId: spec.release.id,
    },
    meter: { kind: 'repeat_template', span: template },
    tempo: { kind: 'inherit_entry' },
    primarySourceSpan: null,
    guitarMode: spec.mode,
    leadership: spec.leadership,
    voices: { guitar: spec.guitar, bass: spec.bass },
    development: quoted(spec.motifIds, spec.returnId, spec.motifIds.length > 0),
    harmony: { policy: 'performer_intent', sourceSpan: null, vocabularyRefs: [], instruction: 'No new harmony and no new pitches.' },
    cues: spec.cues,
    exchanges: spec.motifIds.length
      ? [
          {
            id: `${spec.id}-exchange`,
            initiator: spec.leadership === 'guitar' ? 'guitar' : 'bass',
            responder: spec.leadership === 'guitar' ? 'bass' : 'guitar',
            motifIds: spec.motifIds,
            proposalCueId: spec.release.id,
            responseCueId: exchangeCue.id,
            relation: spec.relation,
            retainedAnchor: spec.motifIds[0]!,
            returnSectionId: spec.returnId,
            execution: 'performer_directed',
          },
        ]
      : [],
    rationale: spec.rationale,
    authorisedSubstitution: null,
  };
}

function performer(motifId: string, instruction: string): VoicePlan['material'] {
  return { kind: 'performer', motifIds: [motifId], instruction };
}

function chordSpan(duo: SourceIndex, arrangement: SourceIndex, first: number, last: number): { duo: Span; arrangement: Span } {
  const alignment = alignChordMelody(duo, arrangement);
  if (!alignment.ok) throw new Error(alignment.message);
  const pair = (order: number) => alignment.pairs.find((item) => item.duoOrder === order);
  const start = pair(first);
  const end = pair(last);
  const before = pair(first - 1);
  if (!start || !end || !before) throw new Error(`chord-melody map misses duo ${first}..${last}`);
  const into = switchIsSafe(duo, arrangement, first - 1, before.arrangementOrder);
  const out = switchIsSafe(duo, arrangement, last, end.arrangementOrder);
  if (!into.safe || !out.safe) throw new Error(`chord-melody span ${first}..${last} is unsafe: ${into.reason}; ${out.reason}`);
  return {
    duo: spanOf(duo, first, last),
    arrangement: spanOf(arrangement, start.arrangementOrder, end.arrangementOrder),
  };
}

