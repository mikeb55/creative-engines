export function proposeV73cPlan(piece: V73cPiece, duo: SourceIndex, arrangement: SourceIndex | null): PerformancePlan {
  if (piece.key === 'black-aura') {
    if (!arrangement) throw new Error('Black Aura needs chord-melody V1.1');
    return blackAura(duo, arrangement);
  }
  if (piece.key === 'the-mirror') {
    if (!arrangement) throw new Error('The Mirror needs the alternate arrangement');
    const plan = proposeMirrorPlanC(duo, arrangement);
    plan.id = 'the-mirror-v73c';
    plan.notes = [...plan.notes, 'V7.3C album plan. Same verified chord-melody span and dialogue as V7.3B Plan C.'];
    return plan;
  }
  if (arrangement) throw new Error(`${piece.title} has no authorised chord melody in V7.3C`);
  if (piece.key === 'palace-gates') return palace(duo);
  if (piece.key === 'meet-me-at-hobos') return hobo(duo);
  if (piece.key === 'orbit') return orbit(duo);
  if (piece.key === 'wrong-turning') return wrong(duo);
  if (piece.key === 'impossible-metaphysics') return impossible(duo);
  if (piece.key === 'small-testimony') return small(duo);
  if (piece.key === 'after-everything') return afterEverything(duo);
  throw new Error(`unknown piece ${piece.key}`);
}
