/**
 * Create ~/Desktop/Composer OS.app — Finder-launchable wrapper that rebuilds
 * from the current working tree, then starts Electron.
 * macOS only. Windows shortcut path is installDesktopIcon.ts (untouched).
 */
import { execFileSync, execSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

export const LAUNCHER_APP_NAME = 'Composer OS.app';
export const LAUNCHER_BUNDLE_ID = 'com.mikeb55.composeros.launcher';
export const LAUNCHER_DISPLAY_NAME = 'Composer OS';

export type CreateDesktopLauncherMacResult = {
  bundlePath: string;
  nodePath: string;
  npmPath: string;
  repoRoot: string;
  electronPath: string;
  icnsPath: string;
};

function shSingleQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

export function resolveNpmPath(): string {
  const fromWhich = execSync('which npm', { encoding: 'utf8' }).trim();
  if (!fromWhich || !fs.existsSync(fromWhich)) {
    throw new Error('Could not resolve npm (which npm).');
  }
  // Keep the shim (`/usr/local/bin/npm`), not the resolved npm-cli.js path.
  return fromWhich;
}

export function resolveElectronPath(desktopAppRoot: string): string {
  const electron = path.join(
    desktopAppRoot,
    'node_modules',
    'electron',
    'dist',
    'Electron.app',
    'Contents',
    'MacOS',
    'Electron'
  );
  return electron;
}

export function resolveRepoRoot(desktopAppRoot: string): string {
  return path.resolve(desktopAppRoot, '..', '..');
}

export function desktopLauncherBundlePath(homeDir = os.homedir()): string {
  return path.join(homeDir, 'Desktop', LAUNCHER_APP_NAME);
}

export function buildLaunchScript(args: {
  nodePath: string;
  npmPath: string;
  repoRoot: string;
  desktopAppRoot: string;
  electronPath: string;
}): string {
  const node = shSingleQuote(args.nodePath);
  const npm = shSingleQuote(args.npmPath);
  const repo = shSingleQuote(args.repoRoot);
  const desktop = shSingleQuote(args.desktopAppRoot);
  const electron = shSingleQuote(args.electronPath);

  return `#!/bin/bash
# Generated by desktop:create-launcher:mac — do not edit by hand.
# Finder launches have no nvm/Homebrew PATH; node/npm/repo are baked in.

NODE=${node}
NPM=${npm}
REPO=${repo}
DESKTOP=${desktop}
ELECTRON=${electron}
TMP="$DESKTOP/tmp"
STAMP="$TMP/launcher-fingerprint.txt"
FINGERPRINT_JS="$DESKTOP/scripts/launcherFingerprint.js"
VERIFY_JS="$DESKTOP/scripts/verify-ui-after-copy.js"

export PATH="$(dirname "$NODE"):$(dirname "$NPM"):/usr/bin:/bin:/usr/sbin:/sbin"
unset npm_config_devdir

show_missing_node() {
  /usr/bin/osascript -e 'display dialog "Composer OS cannot find Node at the path baked into this launcher.\\n\\nRe-run from the repo:\\nnpm run desktop:create-launcher:mac" buttons {"OK"} default button "OK" with title "Composer OS"' >/dev/null
  exit 1
}

show_build_failed() {
  local log="$1"
  local excerpt
  excerpt="$(/usr/bin/tail -n 15 "$log" | /usr/bin/tr -d '\\r')"
  /usr/bin/osascript - "$log" "$excerpt" <<'APPLESCRIPT'
on run argv
  set logPath to item 1 of argv
  set excerpt to item 2 of argv
  set theBtn to button returned of (display dialog excerpt buttons {"Open Log", "OK"} default button "Open Log" with title "Composer OS build failed")
  if theBtn is "Open Log" then
    do shell script "open -a TextEdit " & quoted form of logPath
  end if
end run
APPLESCRIPT
}

if [ ! -x "$NODE" ]; then
  show_missing_node
fi
if [ ! -x "$NPM" ]; then
  /usr/bin/osascript -e 'display dialog "Composer OS cannot find npm at the baked path. Re-run npm run desktop:create-launcher:mac" buttons {"OK"} default button "OK" with title "Composer OS"' >/dev/null
  exit 1
fi

/bin/mkdir -p "$TMP"

if /usr/bin/pgrep -f "/apps/composer-os-desktop/node_modules/electron/dist/Electron.app/Contents/MacOS/Electron" >/dev/null 2>&1; then
  cd "$DESKTOP" || exit 1
  exec "$ELECTRON" .
fi

FP="$("$NODE" "$FINGERPRINT_JS" "$REPO")" || {
  /usr/bin/osascript -e 'display dialog "Composer OS could not fingerprint the working tree. Is git available at /usr/bin/git?" buttons {"OK"} default button "OK" with title "Composer OS"' >/dev/null
  exit 1
}

OLD=""
if [ -f "$STAMP" ]; then
  OLD="$(/bin/cat "$STAMP")"
fi

FAST=0
if [ -n "$FP" ] && [ "$FP" = "$OLD" ] && [ -x "$ELECTRON" ] && [ -f "$DESKTOP/resources/ui/composer-os-ui-stamp.json" ]; then
  if (cd "$DESKTOP" && "$NODE" "$VERIFY_JS") >/dev/null 2>&1; then
    FAST=1
  fi
fi

if [ "$FAST" = "1" ]; then
  cd "$DESKTOP" || exit 1
  exec "$ELECTRON" .
fi

/usr/bin/osascript -e 'display notification "Composer OS — rebuilding latest changes…" with title "Composer OS"' >/dev/null

TS="$(/bin/date +%Y%m%d-%H%M%S)"
LOG="$TMP/launcher-$TS.log"

{
  echo "Composer OS launcher rebuild $TS"
  echo "repo=$REPO"
  echo "node=$NODE"
  echo "npm=$NPM"
  echo "fingerprint=$FP"
} >"$LOG"

cd "$DESKTOP" || exit 1
set +e
{
  "$NPM" run build:icon &&
  "$NODE" scripts/copy-pdfjs-desktop-assets.js &&
  "$NPM" run build:api &&
  "$NPM" run build:desktop-ipc &&
  "$NPM" run build:stamp &&
  "$NPM" run build:open-folder-helpers &&
  "$NPM" run build:electron &&
  "$NPM" run build:ui &&
  "$NPM" run verify:ui-resources
} >>"$LOG" 2>&1
RC=$?
set -e

if [ "$RC" -ne 0 ]; then
  show_build_failed "$LOG"
  exit "$RC"
fi

printf '%s\\n' "$FP" >"$STAMP"

if [ ! -x "$ELECTRON" ]; then
  /usr/bin/osascript -e 'display dialog "Electron binary missing after build. Run npm install in apps/composer-os-desktop." buttons {"OK"} default button "OK" with title "Composer OS"' >/dev/null
  exit 1
fi

exec "$ELECTRON" .
`;
}

function writeInfoPlist(plistPath: string): void {
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>${LAUNCHER_DISPLAY_NAME}</string>
  <key>CFBundleDisplayName</key>
  <string>${LAUNCHER_DISPLAY_NAME}</string>
  <key>CFBundleExecutable</key>
  <string>launch</string>
  <key>CFBundleIconFile</key>
  <string>icon</string>
  <key>CFBundleIdentifier</key>
  <string>${LAUNCHER_BUNDLE_ID}</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>1.0</string>
  <key>CFBundleVersion</key>
  <string>1.0</string>
  <key>LSMinimumSystemVersion</key>
  <string>12.0</string>
  <key>LSUIElement</key>
  <false/>
</dict>
</plist>
`;
  fs.writeFileSync(plistPath, xml);
}

function ensureIcns(desktopAppRoot: string, destIcns: string): string {
  const srcIcns = path.join(desktopAppRoot, 'resources', 'icon.icns');
  if (!fs.existsSync(srcIcns)) {
    const generate = path.join(desktopAppRoot, 'scripts', 'generate-icon.js');
    console.log('[desktop] icon.icns missing — generating via generate-icon.js');
    execFileSync(process.execPath, [generate], { cwd: desktopAppRoot, stdio: 'inherit' });
  }
  if (!fs.existsSync(srcIcns)) {
    throw new Error(`Failed to produce icon.icns at ${srcIcns}`);
  }
  fs.copyFileSync(srcIcns, destIcns);
  return destIcns;
}

function signClearAndTouch(bundlePath: string): void {
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', bundlePath], { stdio: 'inherit' });
  try {
    execFileSync('xattr', ['-dr', 'com.apple.quarantine', bundlePath], { stdio: 'inherit' });
  } catch {
    /* no quarantine xattr */
  }
  execFileSync('touch', [bundlePath], { stdio: 'inherit' });
}

export function createDesktopLauncherMac(desktopAppRoot: string): CreateDesktopLauncherMacResult {
  if (process.platform !== 'darwin') {
    throw new Error('desktop:create-launcher:mac requires macOS.');
  }

  const root = path.resolve(desktopAppRoot);
  const repoRoot = resolveRepoRoot(root);
  const nodePath = fs.realpathSync(process.execPath);
  const npmPath = resolveNpmPath();
  const electronPath = resolveElectronPath(root);
  const bundlePath = desktopLauncherBundlePath();

  console.log('[desktop] creating launcher bundle');
  console.log('[desktop] node:', nodePath);
  console.log('[desktop] npm:', npmPath);
  console.log('[desktop] repo:', repoRoot);
  console.log('[desktop] electron:', electronPath);
  console.log('[desktop] dest:', bundlePath);

  if (fs.existsSync(bundlePath)) {
    fs.rmSync(bundlePath, { recursive: true, force: true });
  }

  const contents = path.join(bundlePath, 'Contents');
  const macos = path.join(contents, 'MacOS');
  const resources = path.join(contents, 'Resources');
  fs.mkdirSync(macos, { recursive: true });
  fs.mkdirSync(resources, { recursive: true });

  writeInfoPlist(path.join(contents, 'Info.plist'));
  const icnsPath = ensureIcns(root, path.join(resources, 'icon.icns'));

  const launchPath = path.join(macos, 'launch');
  fs.writeFileSync(
    launchPath,
    buildLaunchScript({
      nodePath,
      npmPath,
      repoRoot,
      desktopAppRoot: root,
      electronPath,
    }),
    { mode: 0o755 }
  );
  fs.chmodSync(launchPath, 0o755);

  signClearAndTouch(bundlePath);

  console.log('[desktop] signed + quarantine cleared');
  return { bundlePath, nodePath, npmPath, repoRoot, electronPath, icnsPath };
}
